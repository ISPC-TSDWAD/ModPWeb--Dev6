@Injectable({ providedIn: 'root' })
export class I18nService {
  private _lang: Lang = 'es';

  constructor() {
    const guardado = localStorage.getItem('lang');
    this.setLang(guardado === 'en' ? 'en' : 'es');
  }

  get lang(): Lang {
    return this._lang;
  }

  setLang(lang: Lang): void {
    this._lang = lang;
    localStorage.setItem('lang', lang);
    document.documentElement.lang = lang;
  }

  /** Devuelve la traducción de la clave para el idioma actual. */
  t(key: string): string {
    return DICT[this._lang][key] ?? DICT.es[key] ?? key;
  }
}
